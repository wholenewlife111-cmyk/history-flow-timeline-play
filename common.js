async function act(o) {
  if (!REMOTE) { const st = loadLocal(); const r = applyAction(st, Object.assign({}, o), o.code); if (r.ok) saveLocal(r.st); return r; }
  const r = await fetch(API, { method: 'POST', headers: { 'Content-Type': 'text/plain;charset=utf-8' }, body: JSON.stringify(Object.assign({ cls: CLASS }, o)) });
  return r.json();
}
async function apiGet(v) {
  const u = API + (API.includes('?') ? '&' : '?') + 'a=state&cls=' + encodeURIComponent(CLASS) + '&v=' + (v ?? '');
  const r = await fetch(u, { cache: 'no-store' }); return r.json();
}
async function apiCheck(code) {
  if (!REMOTE) return true;
  const r = await fetch(API + (API.includes('?') ? '&' : '?') + 'a=check&code=' + encodeURIComponent(code), { cache: 'no-store' });
  return (await r.json()).ok;
}
function syncState(fn, ms) {
  if (!REMOTE) { window.addEventListener('storage', e => { if (e.key === KEY) fn(loadLocal()); }); fn(loadLocal()); setNet(true); return; }
  let v = '', busy = false;
  const tick = async () => {
    if (busy || syncState.hold) return; busy = true;
    try { const d = await apiGet(v); if (d.ok && !d.same && d.st) { v = d.v; fn(Object.assign(freshState(), d.st)); } setNet(true); } catch (e) { setNet(false); }
    busy = false;
  };
  syncState.now = () => { v = ''; tick(); };
  tick(); setInterval(tick, ms);
}
