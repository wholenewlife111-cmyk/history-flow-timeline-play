const PATCH_KEYS = ['lesson', 'phase', 'ring', 'names', 'pending', 'used', 'leaders', 'passUsed', 'done', 'linked', 'stdShown', 'help'];
function applyAction(st, d, code) {
  const clip = (s, n) => String(s == null ? '' : s).slice(0, n);
  const rid = p => p + st.v + '_' + Math.floor(Math.random() * 1e6);
  st.help = st.help || []; st.clues = st.clues || [];
  if (d.a === 'card') {
    const c = d.card || {};
    if (st.cards.length >= 500) return { ok: false, msg: 'full' };
    const cd = { id: rid('c'), ring: Math.max(0, Math.min(3, +c.ring || 0)), k: ['c', 'r', 'q'].includes(c.k) ? c.k : 'c',
      t: clip(c.t, 200), page: clip(c.page, 60), q: clip(c.q, 200), g: clip(c.g, 3), p: clip(c.p, 2), who: clip(c.who, 10), fresh: true };
    cd.m = cd.g + '모둠 짝 ' + cd.p + (cd.k === 'q' ? '' : ' · ' + (cd.page || '근거 없음'));
    if (!cd.t.trim()) return { ok: false, msg: 'empty' };
    st.cards.push(cd); return { ok: true, st, log: cd };
  }
  if (d.a === 'help') {
    if (st.help.length >= 200) return { ok: false };
    st.help.push({ id: rid('h'), ring: +d.ring || 0, g: clip(d.g, 3), reason: clip(d.reason, 30), helpers: [], done: false });
    return { ok: true, st };
  }
  if (d.a === 'clue') {
    if (st.clues.length >= 300) return { ok: false };
    const cl = { id: rid('k'), ring: +d.ring || 0, to: clip(d.to, 3), from: clip(d.from, 3), kind: clip(d.kind, 6), t: clip(d.t, 80) };
    if (!cl.t.trim()) return { ok: false, msg: 'empty' };
    st.clues.push(cl);
    st.help.forEach(h => { if (h.g === cl.to && h.ring === cl.ring && !h.done && h.helpers.indexOf(cl.from) < 0) h.helpers.push(cl.from); });
    return { ok: true, st };
  }
  if (d.a === 'volunteer') {
    const n = clip(d.name, 10).trim();
    if (n && st.pending.length < 60 && st.pending.indexOf(n) < 0 && st.names.indexOf(n) < 0) st.pending.push(n);
    return { ok: true, st };
  }
  if (d.code !== code) return { ok: false, msg: 'code' };
  if (d.a === 'reset') { const f = freshState(st.names); f.v = st.v; f.lesson = st.lesson; f.names = st.names; return { ok: true, st: f }; }
  if (d.a === 'patch') {
    const set = d.set || {};
    PATCH_KEYS.forEach(k => { if (k in set) st[k] = set[k]; });
    (d.edits || []).forEach(ed => { const c = st.cards.find(x => x.id === ed.id); if (!c) return; ['k', 'ring', 'ok', 'fresh', 'who'].forEach(k => { if (k in ed) c[k] = ed[k]; }); });
    const del = (d.del || []).map(String); if (del.length) st.cards = st.cards.filter(c => del.indexOf(String(c.id)) < 0);
    (d.add || []).forEach(c => st.cards.push({ id: rid('b'), ring: +c.ring || 0, k: ['c', 'r', 'q'].includes(c.k) ? c.k : 'c', t: clip(c.t, 300), m: clip(c.m, 80), q: clip(c.q, 200), who: clip(c.who, 10), std: !!c.std, ok: !!c.ok, ex: !!c.ex }));
    return { ok: true, st };
  }
  return { ok: false };
}

